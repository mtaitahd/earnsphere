const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const input = {value:'5000',validationMessage:'',setCustomValidity(value){this.validationMessage=value;},addEventListener(event,callback){this.update=callback;}};
const output = {dataset:{charge:'500'},textContent:''};
const consent = {checked:true};
const elements = {'amount':input,'withdrawal-quote':output,'confirm-withdrawal-terms':consent};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../assets/js/withdrawal-charge.js'),'utf8'),{document:{getElementById:id=>elements[id]}});
assert(output.textContent.includes('4,500'),'Net amount missing');
assert(output.textContent.includes('5,000'),'Wallet debit missing');
assert(output.textContent.includes('500'),'Charge missing');
assert.equal(consent.checked,false,'Quote did not require confirmation');
consent.checked=true;input.value='10000';input.update();
assert(output.textContent.includes('9,500'),'Updated net incorrect');
assert.equal(consent.checked,false,'Amount change retained old consent');
input.value='500';input.update();assert(input.validationMessage,'Zero net accepted');
input.value='499';input.update();assert(input.validationMessage,'Negative net accepted');
input.value='1000.5';input.update();assert(input.validationMessage,'Fractional request accepted');
input.value='5000';input.update();assert.equal(input.validationMessage,'');
console.log('Withdrawal charge preview checks passed.');
