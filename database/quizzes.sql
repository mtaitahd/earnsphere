CREATE TABLE IF NOT EXISTS comprehension_quizzes (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(150) NOT NULL, instructions TEXT NOT NULL,
 platform VARCHAR(20) NOT NULL DEFAULT 'none', source_url VARCHAR(600) NOT NULL DEFAULT '', questions JSON NOT NULL,
 reward INT UNSIGNED NOT NULL, slots INT UNSIGNED NOT NULL, paid_count INT UNSIGNED NOT NULL DEFAULT 0,
 status VARCHAR(20) NOT NULL DEFAULT 'active', created_by INT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS comprehension_attempts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, quiz_id INT UNSIGNED NOT NULL, user_id INT UNSIGNED NOT NULL,
 answers JSON NOT NULL, score INT UNSIGNED NOT NULL, question_count INT UNSIGNED NOT NULL, reward INT UNSIGNED NOT NULL DEFAULT 0,
 status VARCHAR(20) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_quiz_user (quiz_id,user_id), KEY idx_quiz_attempt_user (user_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
